def _read_log_slice(
    path: Path,
    *,
    after_line: int | None,
    start_line: int | None,
    end_line: int | None,
    tail: int | None,
) -> tuple[int, list[str], int | None, int | None]:
    """Read a log file once and return the requested slice plus line metadata."""
    if after_line is not None:
        selected_lines: list[str] = []
        total_lines = 0
        with path.open(encoding="utf-8", errors="replace") as handle:
            for total_lines, line in enumerate(handle, start=1):
                if total_lines > after_line:
                    selected_lines.append(line)

        if not selected_lines:
            return total_lines, [], None, None
        return total_lines, selected_lines, after_line + 1, total_lines

    if start_line is not None or end_line is not None:
        selected_lines = []
        total_lines = 0
        requested_start = start_line or 1
        requested_end = end_line
        with path.open(encoding="utf-8", errors="replace") as handle:
            for total_lines, line in enumerate(handle, start=1):
                if total_lines < requested_start:
                    continue
                if requested_end is not None and total_lines > requested_end:
                    continue
                selected_lines.append(line)

        if not selected_lines:
            return total_lines, [], None, None
        returned_end_line = requested_start + len(selected_lines) - 1
        return total_lines, selected_lines, requested_start, returned_end_line

    if tail is None:
        selected_lines = []
        total_lines = 0
        with path.open(encoding="utf-8", errors="replace") as handle:
            for total_lines, line in enumerate(handle, start=1):
                selected_lines.append(line)

        if not selected_lines:
            return total_lines, [], None, None
        return total_lines, selected_lines, 1, total_lines

    if tail == 0:
        total_lines = 0
        with path.open(encoding="utf-8", errors="replace") as handle:
            for total_lines, _line in enumerate(handle, start=1):
                pass
        return total_lines, [], None, None

    selected_tail: deque[str] = deque(maxlen=tail)
    total_lines = 0
    with path.open(encoding="utf-8", errors="replace") as handle:
        for total_lines, line in enumerate(handle, start=1):
            selected_tail.append(line)

    selected_lines = list(selected_tail)
    if not selected_lines:
        return total_lines, [], None, None
    returned_start_line = total_lines - len(selected_lines) + 1
    return total_lines, selected_lines, returned_start_line, total_lines


def _build_important_log_payload(
    record: dict[str, Any],
    job_paths: JobPaths,
    *,
    stream: str,
) -> dict[str, Any]:
    """Return one compact log summary without the raw body."""
    log_path = _log_path_for_stream(record, job_paths, stream)
    payload: dict[str, Any] = {
        "process_id": record["process_id"],
        "status": record["status"],
        "stream": stream,
        "view": "important",
        "path": str(log_path),
        "raw_available": log_path.exists(),
    }

    if not log_path.exists():
        payload.update(
            {
                "category": "empty",
                "summary": f"No {stream} log lines are available yet.",
                "important_lines": [],
                "evidence": [],
            }
        )
        return payload

    if stream == "nextflow" and record["kind"] == "nextflow":
        payload.update(_build_nextflow_important_summary(record, job_paths, log_path))
        return payload

    lines = _read_visible_log_excerpt(log_path, max_lines=IMPORTANT_LOG_EXCERPT_LINES)
    payload.update(
        {
            "category": _build_generic_log_category(record["status"], lines),
            "summary": _build_generic_log_summary(record["status"], stream, lines),
            "important_lines": lines,
            "evidence": [{"source": f"{stream}_log", "path": str(log_path), "lines": lines}],
        }
    )
    return payload


def _build_nextflow_important_summary(
    record: dict[str, Any],
    job_paths: JobPaths,
    log_path: Path,
) -> dict[str, Any]:
    """Summarize nextflow.log and add task-level evidence when available."""
    highlights = _extract_nextflow_highlights(log_path)
    evidence: list[dict[str, Any]] = []
    important_lines = _nextflow_primary_excerpt(record["status"], highlights)
    if important_lines:
        evidence.append(
            {
                "source": "nextflow_log",
                "path": str(log_path),
                "lines": important_lines,
            }
        )

    task_evidence = _load_task_failure_evidence(highlights.work_dir)
    if task_evidence is None:
        stderr_lines = _read_visible_log_excerpt(
            job_paths.stderr_log,
            max_lines=IMPORTANT_LOG_EXCERPT_LINES,
        )
        if stderr_lines:
            task_evidence = {
                "source": "stderr_log",
                "path": str(job_paths.stderr_log),
                "lines": stderr_lines,
            }

    if task_evidence is not None:
        evidence.append(task_evidence)

    merged_lines = _merge_excerpt_lines(
        *(item["lines"] for item in evidence),
        max_lines=IMPORTANT_LOG_EXCERPT_LINES * 2,
    )
    category = _build_nextflow_log_category(record["status"], highlights, task_evidence is not None)

    return {
        "category": category,
        "summary": _build_nextflow_log_summary(category, highlights),
        "warn_count": highlights.warn_count,
        "error_count": highlights.error_count,
        "important_lines": merged_lines,
        "evidence": evidence,
    }


def _read_visible_log_excerpt(path: Path, *, max_lines: int) -> list[str]:
    """Read a small visible excerpt from the end of one log-like file."""
    if not path.exists():
        return []

    _total, lines, _start, _end = _read_log_slice(
        path,
        after_line=None,
        start_line=None,
        end_line=None,
        tail=max(max_lines * 4, IMPORTANT_LOG_FALLBACK_TAIL),
    )
    visible: list[str] = []
    for raw_line in reversed(lines):
        clipped = _clip_log_line(raw_line)
        if not clipped:
            continue
        visible.append(clipped)
        if len(visible) >= max_lines:
            break
    visible.reverse()
    return visible


def _clip_log_line(line: str, *, max_chars: int = IMPORTANT_LOG_MAX_CHARS) -> str:
    """Trim one log line for compact MCP responses."""
    clipped = line.strip()
    if not clipped:
        return ""
    if len(clipped) <= max_chars:
        return clipped
    return f"{clipped[: max_chars - 3]}..."


def _extract_nextflow_highlights(path: Path) -> NextflowLogHighlights:
    """Extract compact task, progress, and failure hints from nextflow.log."""
    warn_count = 0
    error_count = 0
    latest_progress_line = None
    latest_warn_line = None
    latest_error_line = None
    session_aborted_line = None
    caused_by_line = None
    task_line = None
    task_label = None
    work_dir = None
    completed_line = None
    duration_line = None
    fallback_tail: deque[str] = deque(maxlen=IMPORTANT_LOG_FALLBACK_TAIL)
    expect_caused_by_detail = False
    expect_work_dir_value = False

    with path.open(encoding="utf-8", errors="replace") as handle:
        for raw_line in handle:
            clipped = _clip_log_line(raw_line)
            if clipped:
                fallback_tail.append(clipped)

            stripped = raw_line.strip()
            if not stripped:
                continue

            upper = stripped.upper()
            if "EXECUTOR >" in upper:
                latest_progress_line = clipped
            if upper.startswith("WARN") or " WARN" in upper or "WARNING" in upper:
                warn_count += 1
                latest_warn_line = clipped
            if upper.startswith("ERROR") or " ERROR" in upper:
                error_count += 1
                latest_error_line = clipped

            if "Error executing process >" in stripped:
                error_count += 1
                task_line = clipped
                latest_error_line = clipped
                match = NEXTFLOW_PROCESS_ERROR_RE.search(stripped)
                if match is not None:
                    task_label = match.group(1)
            if "Session aborted" in stripped or "Execution cancelled" in stripped:
                error_count += 1
                session_aborted_line = clipped
                latest_error_line = clipped
            if "Completed at:" in stripped:
                completed_line = clipped
            if "Duration    :" in stripped or stripped.startswith("Duration:"):
                duration_line = clipped

            caused_by_value = _extract_label_value(stripped, "Caused by:")
            if caused_by_value is not None:
                expect_caused_by_detail = caused_by_value == ""
                if caused_by_value:
                    caused_by_line = _clip_log_line(caused_by_value)
                continue
            if expect_caused_by_detail:
                caused_by_line = clipped
                expect_caused_by_detail = False

            work_dir_value = _extract_label_value(stripped, "Work dir:")
            if work_dir_value is not None:
                expect_work_dir_value = work_dir_value == ""
                if work_dir_value:
                    work_dir = work_dir_value
                continue
            if expect_work_dir_value:
                work_dir = stripped
                expect_work_dir_value = False

    return NextflowLogHighlights(
        warn_count=warn_count,
        error_count=error_count,
        latest_progress_line=latest_progress_line,
        latest_warn_line=latest_warn_line,
        latest_error_line=latest_error_line,
        session_aborted_line=session_aborted_line,
        caused_by_line=caused_by_line,
        task_line=task_line,
        task_label=task_label,
        work_dir=work_dir,
        completed_line=completed_line,
        duration_line=duration_line,
        fallback_tail=tuple(fallback_tail),
    )


def _extract_label_value(line: str, label: str) -> str | None:
    """Extract an optional value that follows one `Label:` marker."""
    if label not in line:
        return None
    _prefix, _sep, suffix = line.partition(label)
    return suffix.strip()


def _extract_nextflow_session_uuid(path: Path) -> str | None:
    """Read a small head slice from nextflow.log and extract the session UUID."""
    if not path.exists():
        return None

    try:
        with path.open(encoding="utf-8", errors="replace") as handle:
            for index, line in enumerate(handle):
                match = NEXTFLOW_SESSION_UUID_RE.search(line)
                if match is not None:
                    return match.group(1).lower()
                if index >= 200:
                    break
    except OSError:
        return None
    return None


def _is_resume_candidate_compatible(payload: dict[str, Any]) -> bool:
    """Return whether one stored Nextflow run still has the minimum resume inputs."""
    session_uuid = payload.get("nextflow_session_uuid")
    if not isinstance(session_uuid, str) or not session_uuid:
        return False

    run_root_value = payload.get("cwd")
    if (
        not isinstance(run_root_value, str)
        or not run_root_value
        or not Path(run_root_value).exists()
    ):
        return False

    work_dir_value = payload.get("work_dir")
    if not isinstance(work_dir_value, str) or not work_dir_value:
        return False
    return Path(work_dir_value).exists()


def _load_task_failure_evidence(work_dir: str | None) -> dict[str, Any] | None:
    """Read one bounded task-level failure excerpt from a Nextflow work dir."""
    if work_dir is None:
        return None

    work_path = Path(work_dir)
    candidates = (
        ("task_command_err", work_path / ".command.err"),
        ("task_command_log", work_path / ".command.log"),
    )
    for source, path in candidates:
        lines = _read_visible_log_excerpt(path, max_lines=IMPORTANT_LOG_EXCERPT_LINES)
        if lines:
            return {
                "source": source,
                "path": str(path),
                "lines": lines,
            }
    return None


def _merge_excerpt_lines(*groups: list[str], max_lines: int) -> list[str]:
    """Merge compact line groups while keeping order and removing duplicates."""
    merged: list[str] = []
    for group in groups:
        for line in group:
            if not line or line in merged:
                continue
            merged.append(line)
            if len(merged) >= max_lines:
                return merged
    return merged


def _nextflow_primary_excerpt(status: str, highlights: NextflowLogHighlights) -> list[str]:
    """Build a small nextflow.log excerpt ordered by diagnostic value."""
    candidates: list[str] = []
    if highlights.task_line is not None:
        candidates.append(highlights.task_line)
    if highlights.caused_by_line is not None:
        candidates.append(highlights.caused_by_line)
    if highlights.session_aborted_line is not None:
        candidates.append(highlights.session_aborted_line)
    if highlights.latest_error_line is not None:
        candidates.append(highlights.latest_error_line)
    if status == "running" and highlights.latest_progress_line is not None:
        candidates.append(highlights.latest_progress_line)
    if status == "succeeded":
        if highlights.completed_line is not None:
            candidates.append(highlights.completed_line)
        if highlights.duration_line is not None:
            candidates.append(highlights.duration_line)
    if highlights.latest_warn_line is not None and not candidates:
        candidates.append(highlights.latest_warn_line)
    if not candidates:
        candidates.extend(
            [
                line
                for line in highlights.fallback_tail
                if NEXTFLOW_SESSION_UUID_RE.search(line) is None
            ]
        )
    if not candidates:
        candidates.extend(list(highlights.fallback_tail))
    return _merge_excerpt_lines(candidates, max_lines=IMPORTANT_LOG_EXCERPT_LINES)


def _build_nextflow_log_category(
    status: str,
    highlights: NextflowLogHighlights,
    has_task_evidence: bool,
) -> str:
    """Classify one important nextflow log summary."""
    if has_task_evidence or highlights.task_line is not None or highlights.work_dir is not None:
        return "task_failure"
    if highlights.error_count > 0 or highlights.caused_by_line is not None:
        return "framework_error"
    if status == "running":
        return "running"
    if status == "succeeded":
        return "succeeded"
    if highlights.warn_count > 0:
        return "warnings_only"
    return "log_excerpt"


def _build_nextflow_log_summary(category: str, highlights: NextflowLogHighlights) -> str:
    """Render a compact summary for one nextflow important-log payload."""
    if category == "task_failure":
        if highlights.task_label is not None:
            return f"Task failed inside process {highlights.task_label}."
        return "A Nextflow task failed. Read the task-level evidence first."
    if category == "framework_error":
        return "Nextflow reported a framework-level failure."
    if category == "running":
        return "Nextflow run is still active."
    if category == "succeeded":
        return "Nextflow run finished successfully."
    if category == "warnings_only":
        return "Nextflow log contains warnings."
    return "Returning recent important Nextflow log lines."


def _build_generic_log_category(status: str, lines: list[str]) -> str:
    """Classify a compact stdout/stderr excerpt."""
    if not lines:
        return "empty"
    if status == "running":
        return "running"
    if status == "succeeded":
        return "succeeded"
    if status == "failed":
        return "failed"
    return "log_excerpt"


def _build_generic_log_summary(status: str, stream: str, lines: list[str]) -> str:
    """Render one short summary for stdout/stderr important view."""
    if not lines:
        return f"No visible {stream} log lines are available yet."
    if status == "running":
        return f"Returning recent {stream} lines from the active run."
    if status == "succeeded":
        return f"Returning recent {stream} lines from the finished run."
    if status == "failed":
        return f"Returning recent {stream} lines from the failed run."
    return f"Returning recent important lines from {stream}."


