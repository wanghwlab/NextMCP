def _build_nextflow_pipeline_fingerprint(
    *,
    pipeline: str,
    local_pipeline: LocalPipeline | None,
    expose_materials: bool,
    public_target: str,
) -> dict[str, Any]:
    """Build a lightweight pipeline fingerprint for historical artifact reuse."""
    if local_pipeline is None:
        return {
            "mode": "remote_unpinned",
            "target": pipeline,
            "digest": None,
        }

    hasher = sha256()
    seen_paths: set[Path] = set()
    source_paths = [
        local_pipeline.main_script,
        local_pipeline.nextflow_config,
        local_pipeline.schema_path,
        *local_pipeline.entry_scripts,
        *local_pipeline.workflow_scripts,
    ]
    for path in sorted(
        (item for item in source_paths if item is not None and item.is_file()),
        key=lambda value: str(value),
    ):
        if path in seen_paths:
            continue
        seen_paths.add(path)
        hasher.update(str(path).encode("utf-8"))
        hasher.update(b"\0")
        hasher.update(path.read_bytes())
        hasher.update(b"\0")

    target = str(local_pipeline.main_script) if expose_materials else public_target
    return {
        "mode": "local",
        "target": target,
        "digest": f"sha256:{hasher.hexdigest()}",
    }


def _public_pipeline_value(pipeline: str) -> str:
    """Return a pipeline value safe for public payloads."""
    pipeline_path = Path(pipeline)
    if pipeline_path.is_absolute() or pipeline.startswith("."):
        return PIPELINE_MATERIALS_REDACTION
    return pipeline


def _resolve_nextflow_work_dir(
    guard: PathGuard,
    *,
    cwd: Path,
    work_dir: str | None,
) -> tuple[str, str]:
    """Resolve the final Nextflow work directory and record where it came from."""
    if work_dir is None:
        return str(guard.resolve_write("work", str(cwd))), "default_cwd_work"
    return str(guard.resolve_write(work_dir, str(cwd))), "explicit"


def _derive_primary_results_dir(
    *,
    cwd: Path,
    params: dict[str, str],
) -> tuple[str | None, str | None]:
    """Derive one primary workflow results directory from a small param allowlist."""
    outdir = params.get("outdir")
    if isinstance(outdir, str) and outdir:
        return str(_resolve_candidate_path(outdir, cwd)), "params.outdir"

    candidates: list[tuple[str, str, str]] = []
    for key in PRIMARY_RESULTS_DIR_PARAM_KEYS:
        if key == "outdir":
            continue
        value = params.get(key)
        if not isinstance(value, str) or not value:
            continue
        candidates.append((key, value, str(_resolve_candidate_path(value, cwd))))

    if not candidates:
        return None, None

    unique_paths = {resolved_path for _key, _value, resolved_path in candidates}
    if len(unique_paths) > 1:
        rendered = ", ".join(
            f"`{key}` -> {resolved_path}" for key, _value, resolved_path in candidates
        )
        raise ValueError(
            "Conflicting primary results directory params; do not guess between multiple "
            f"candidates: {rendered}"
        )

    key, _value, resolved_path = candidates[0]
    return resolved_path, f"params.{key}"


def _build_run_layout(
    *,
    run_root: Path,
    work_dir: str,
    work_dir_source: str,
    params: dict[str, str],
    job_dir: Path,
    reserved_results_dir: str | None = None,
) -> tuple[dict[str, Any], list[dict[str, str]]]:
    """Build one stable run-layout summary for prepare/full payloads."""
    results_dir, results_dir_source = _derive_primary_results_dir(cwd=run_root, params=params)
    if results_dir is None and reserved_results_dir is not None:
        results_dir = reserved_results_dir
        results_dir_source = "project.default"

    warnings: list[dict[str, str]] = []
    if work_dir_source == "default_cwd_work":
        warnings.append(
            {
                "kind": "work_dir_defaulted",
                "message": (f"No explicit work_dir was provided. nextmcp will use {work_dir}."),
            }
        )
    if results_dir is None:
        warnings.append(
            {
                "kind": "missing_primary_results_dir",
                "message": (
                    "Could not determine a primary results directory from params. "
                    "Set one of `outdir`, `output`, `output_dir`, `results`, or "
                    "`results_dir` if the pipeline exposes one."
                ),
            }
        )
    elif results_dir_source == "project.default":
        warnings.append(
            {
                "kind": "primary_results_dir_unbound",
                "message": (
                    "Reserved a project-local results directory, but the pipeline did not expose "
                    "a recognized primary results-dir param."
                ),
            }
        )

    return (
        {
            "run_root": str(run_root),
            "work_dir": work_dir,
            "work_dir_source": work_dir_source,
            "results_dir": results_dir,
            "results_dir_source": results_dir_source,
            "job_dir": str(job_dir),
        },
        warnings,
    )


def _extra_args_include_params_file(extra_args: list[str]) -> bool:
    """Check whether raw extra args include a Nextflow params-file flag."""
    for arg in extra_args:
        if arg in {"-params-file", "--params-file"}:
            return True
        if arg.startswith("-params-file=") or arg.startswith("--params-file="):
            return True
    return False


def _summarize_nextflow_schema_errors(errors: list[dict[str, str]]) -> str:
    """Render compact human-readable schema validation errors."""
    rendered: list[str] = []
    for error in errors:
        kind = error.get("kind")
        param = error.get("param", "<unknown>")
        if kind == "type_mismatch":
            rendered.append(
                f"param `{param}` expected {error.get('expected', 'unknown')} but got "
                f"{error.get('actual', 'unknown')}"
            )
            continue
        if kind == "missing_required":
            rendered.append(f"missing required param `{param}`")
            continue
        rendered.append(error.get("message", f"schema validation failed for `{param}`"))
    return "Schema validation failed: " + "; ".join(rendered)


def _build_nextflow_expected_artifacts(
    *,
    cwd: Path,
    job_paths: JobPaths,
    command_extra: dict[str, Any],
    launched: bool,
    include_runtime_items: bool = True,
) -> dict[str, Any]:
    """Build a compact artifact manifest from a Nextflow launch plan."""
    items: list[dict[str, Any]] = []
    if include_runtime_items:
        items.extend(
            [
                _artifact_item(
                    job_paths.job_dir,
                    label="job_dir",
                    kind="dir",
                    when="created_on_launch",
                ),
                _artifact_item(
                    job_paths.nextflow_log,
                    label="nextflow_log",
                    kind="file",
                    when="created_on_launch",
                ),
            ]
        )

    work_dir = command_extra.get("work_dir")
    if isinstance(work_dir, str) and work_dir:
        items.append(
            _artifact_item(
                Path(work_dir),
                label="work_dir",
                kind="dir",
                when="produced_on_success" if launched else "used_on_launch",
            )
        )

    params = command_extra.get("params")
    if isinstance(params, dict):
        outdir = params.get("outdir")
        if isinstance(outdir, str) and outdir:
            items.append(
                _artifact_item(
                    _resolve_candidate_path(outdir, cwd),
                    label="outdir",
                    kind="dir",
                    when="produced_on_success",
                )
            )

    extra_args = command_extra.get("extra_args")
    if isinstance(extra_args, list):
        for label, raw_path in _nextflow_output_flag_paths(extra_args):
            items.append(
                _artifact_item(
                    _resolve_candidate_path(raw_path, cwd),
                    label=label,
                    kind="file",
                    when="produced_on_success",
                )
            )

    present_count = sum(1 for item in items if item["exists"])
    return {
        "items": items,
        "present_count": present_count,
        "absent_count": len(items) - present_count,
    }


def _nextflow_output_flag_paths(extra_args: list[Any]) -> list[tuple[str, str]]:
    """Extract declared output file paths from common Nextflow flags."""
    parsed: list[tuple[str, str]] = []
    flag_names = {
        "-with-report": "report",
        "-with-trace": "trace",
        "-with-timeline": "timeline",
        "-with-dag": "dag",
    }

    index = 0
    while index < len(extra_args):
        raw_arg = extra_args[index]
        arg = str(raw_arg)
        matched_inline = False
        for flag, label in flag_names.items():
            prefix = f"{flag}="
            if arg.startswith(prefix):
                parsed.append((label, arg[len(prefix) :]))
                matched_inline = True
                break
        if matched_inline:
            index += 1
            continue
        matched_label = flag_names.get(arg)
        if matched_label is not None and index + 1 < len(extra_args):
            parsed.append((matched_label, str(extra_args[index + 1])))
            index += 2
            continue
        index += 1

    return parsed


def _artifact_item(path: Path, *, label: str, kind: str, when: str) -> dict[str, Any]:
    """Build one compact artifact descriptor."""
    exists = path.exists()
    size = None
    mtime = None
    if exists:
        try:
            stat_result = path.stat()
            if path.is_file():
                size = int(stat_result.st_size)
            mtime = (
                datetime.fromtimestamp(stat_result.st_mtime, tz=timezone.utc)
                .isoformat(timespec="seconds")
                .replace("+00:00", "Z")
            )
        except OSError:
            exists = False

    return {
        "label": label,
        "path": str(path),
        "kind": kind,
        "when": when,
        "exists": exists,
        "size": size,
        "mtime": mtime,
    }


def _artifact_entry(path: Path, *, root_label: str, rel_path: str) -> dict[str, Any]:
    """Build one scanned artifact entry under a published root."""
    stat_result = path.stat()
    return {
        "path": str(path),
        "root_label": root_label,
        "rel_path": rel_path,
        "type": "file" if path.is_file() else "dir",
        "size": int(stat_result.st_size) if path.is_file() else None,
        "mtime": (
            datetime.fromtimestamp(stat_result.st_mtime, tz=timezone.utc)
            .isoformat(timespec="seconds")
            .replace("+00:00", "Z")
        ),
    }


def _maybe_write_nextflow_artifacts_manifest(
    record: dict[str, Any],
    job_paths: JobPaths,
    store: ProcessStore | None = None,
) -> dict[str, Any] | None:
    """Write one Nextflow artifact manifest when enough metadata is available."""
    if record["kind"] != "nextflow":
        return None

    command = read_json(job_paths.command_json)
    if command is None:
        return None

    manifest = _build_nextflow_artifacts_manifest(
        record=record,
        job_paths=job_paths,
        command=command,
    )
    write_json(job_paths.artifacts_json, manifest)
    if store is not None:
        store.replace_artifact_items(
            record["process_id"],
            published_roots=manifest["published_roots"],
            items=manifest["items"],
        )
    return manifest


def _build_nextflow_artifacts_manifest(
    *,
    record: dict[str, Any],
    job_paths: JobPaths,
    command: dict[str, Any],
) -> dict[str, Any]:
    """Build a bounded artifact manifest for one Nextflow run."""
    cwd = Path(record["cwd"])
    declared_outputs = _build_nextflow_expected_artifacts(
        cwd=cwd,
        job_paths=job_paths,
        command_extra=command,
        launched=record["status"] == "succeeded",
        include_runtime_items=False,
    )["items"]
    published_roots = [
        {
            "label": str(item["label"]),
            "path": str(item["path"]),
            "kind": str(item["kind"]),
            "exists": bool(item["exists"]),
            "size": item["size"],
            "mtime": item["mtime"],
        }
        for item in declared_outputs
        if str(item["label"]) != "work_dir"
    ]
    items, truncated = _scan_published_roots(published_roots, max_depth=3, max_items=400)
    return {
        "schema_version": 1,
        "process_id": record["process_id"],
        "kind": record["kind"],
        "status": record["status"],
        "generated_at": _utcnow(),
        "launch": {
            "pipeline": record.get("pipeline_public", record.get("pipeline")),
            "entry": record.get("entry"),
            "profile": record.get("profile"),
            "config_files": record.get("config_files", []),
            "work_dir": record.get("work_dir"),
            "resume": bool(record.get("resume", False)),
            "resume_session_id": record.get("resume_session_id"),
            "extra_args": record.get("extra_args", []),
        },
        "provenance": {
            "cwd": record["cwd"],
            "job_dir": record["job_dir"],
            "command_json": str(job_paths.command_json),
            "nextflow_log": str(job_paths.nextflow_log),
        },
        "pipeline_fingerprint": command.get("pipeline_fingerprint"),
        "published_roots": published_roots,
        "items": items,
        "limits": {
            "max_depth": 3,
            "max_items": 400,
            "truncated": truncated,
        },
    }


def _scan_published_roots(
    published_roots: list[dict[str, Any]],
    *,
    max_depth: int,
    max_items: int,
) -> tuple[list[dict[str, Any]], bool]:
    """Scan published artifact roots with hard depth and item limits."""
    items: list[dict[str, Any]] = []
    for root in published_roots:
        if len(items) >= max_items:
            return items, True

        path = Path(str(root["path"]))
        if not path.exists():
            continue

        label = str(root["label"])
        if path.is_file():
            try:
                items.append(_artifact_entry(path, root_label=label, rel_path=path.name))
            except OSError:
                continue
            continue

        truncated = _scan_artifact_tree(
            root_path=path,
            root_label=label,
            max_depth=max_depth,
            max_items=max_items,
            items=items,
        )
        if truncated:
            return items, True

    return items, False


def _scan_artifact_tree(
    *,
    root_path: Path,
    root_label: str,
    max_depth: int,
    max_items: int,
    items: list[dict[str, Any]],
) -> bool:
    """Scan one artifact directory tree within the configured limits."""
    skipped_dir_names = {"work", "tmp", "temp"}
    stack: list[tuple[Path, int]] = [(root_path, 0)]
    while stack:
        current_dir, depth = stack.pop()
        if depth >= max_depth:
            continue
        try:
            children = sorted(current_dir.iterdir(), key=lambda path: path.name)
        except OSError:
            continue

        subdirs: list[tuple[Path, int]] = []
        for child in children:
            if child.name.startswith("."):
                continue
            if child.is_dir() and child.name in skipped_dir_names:
                continue

            try:
                items.append(
                    _artifact_entry(
                        child,
                        root_label=root_label,
                        rel_path=child.relative_to(root_path).as_posix(),
                    )
                )
            except OSError:
                continue

            if len(items) >= max_items:
                return True
            if child.is_dir() and depth + 1 < max_depth:
                subdirs.append((child, depth + 1))

        stack.extend(reversed(subdirs))
    return False


def _resolve_candidate_path(value: str, cwd: Path) -> Path:
    """Resolve a CLI path-like string against the launch cwd."""
    candidate = Path(value)
    if candidate.is_absolute():
        return candidate.resolve()
    return (cwd / candidate).resolve()


def _is_allowed_path(guard: PathGuard, path: Path, *, role: str) -> bool:
    """Check whether a resolved path stays under the relevant allowlist."""
    try:
        if role == "write":
            guard.check_write(path)
        else:
            guard.check_read(path)
    except PermissionError:
        return False
    return True


def _classify_nextflow_param_path_role(key: str, value: str) -> str | None:
    """Infer whether a Nextflow CLI param looks like a read or write path."""
    lowered_key = key.lower()
    if any(
        token in lowered_key
        for token in ("outdir", "output", "results", "report", "trace", "timeline", "dag", "log")
    ):
        return "write"
    if any(token in lowered_key for token in ("workdir", "work_dir")):
        return "write"
    if _looks_like_path(value):
        return "read"
    return None


def _looks_like_path(value: str) -> bool:
    """Return whether a string is likely to be a filesystem path."""
    if value.startswith(("/", "./", "../", "~")):
        return True
    if "/" in value or "\\" in value:
        return True
    if _looks_like_number(value):
        return False
    return Path(value).suffix != ""


def _looks_like_number(value: str) -> bool:
    """Return whether a string is a plain numeric literal, not a dotted filename."""
    stripped = value.strip()
    if not stripped:
        return False
    try:
        float(stripped)
    except ValueError:
        return False
    return True


def _is_remote_uri(value: str) -> bool:
    """Return whether a string is a non-file URI that should not be resolved as a local path."""
    parsed = urlsplit(value)
    return bool(parsed.scheme and parsed.netloc and parsed.scheme != "file")


def _render_path_check_message(
    *,
    key: str,
    role: str,
    path: Path,
    allowed: bool,
    exists: bool,
) -> str:
    """Render one path-check message for prepare-mode summaries."""
    if role == "read":
        if not allowed:
            return f"Input param `{key}` is outside allowed read roots: {path}"
        if not exists:
            return f"Input param `{key}` points to a missing path: {path}"
        return f"Input param `{key}` resolves to {path}"

    if not allowed:
        return f"Output param `{key}` is outside allowed write roots: {path}"
    return f"Output param `{key}` resolves to {path}"


def _render_remote_reference_check_message(*, key: str, role: str, value: str) -> str:
    """Render one prepare-mode message for a remote URI reference."""
    if role == "read":
        return f"Input param `{key}` uses a remote URI and was not checked as a local path: {value}"
    return f"Output param `{key}` uses a remote URI and was not checked as a local path: {value}"


def _matches_finished_window(
    record: dict[str, Any],
    *,
    finished_after: str | None,
    finished_before: str | None,
) -> bool:
    """Check whether one record falls inside the requested finished_at window."""
    if finished_after is None and finished_before is None:
        return True

    finished_at = record.get("finished_at")
    if not isinstance(finished_at, str):
        return False
    if finished_after is not None and finished_at < finished_after:
        return False
    if finished_before is not None and finished_at > finished_before:
        return False
    return True


def _path_check_warnings(path_checks: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Convert path checks into non-blocking prepare warnings."""
    warnings: list[dict[str, Any]] = []
    for item in path_checks:
        if not item["allowed"]:
            warnings.append(
                {
                    "kind": "path_outside_allowlist",
                    "param": item["param"],
                    "message": item["message"],
                }
            )
            continue
        if item["role"] == "write" and not item["parent_exists"]:
            warnings.append(
                {
                    "kind": "missing_parent_directory",
                    "param": item["param"],
                    "message": (
                        f"Output param `{item['param']}` points to a path whose parent "
                        f"directory does not exist yet: {item['path']}"
                    ),
                }
            )
    return warnings


def _build_process_progress(record: dict[str, Any], job_paths: JobPaths) -> dict[str, Any]:
    """Build a compact progress summary from the preferred log stream."""
    preferred_stream = "nextflow" if record["kind"] == "nextflow" else "stdout"
    preferred_path = _log_path_for_stream(record, job_paths, preferred_stream)
    if not preferred_path.exists() and preferred_stream == "nextflow":
        preferred_stream = "stdout"
        preferred_path = _log_path_for_stream(record, job_paths, preferred_stream)

    if not preferred_path.exists():
        return {
            "state": record["status"],
            "log_stream": preferred_stream,
            "log_total_lines": 0,
            "last_log_line": None,
        }

    total_lines, lines, _start, _end = _read_log_slice(
        preferred_path,
        after_line=None,
        start_line=None,
        end_line=None,
        tail=1,
    )
    last_line = lines[-1].rstrip("\n") if lines else None
    return {
        "state": record["status"],
        "log_stream": preferred_stream,
        "log_total_lines": total_lines,
        "last_log_line": last_line,
    }


