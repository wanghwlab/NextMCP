class ProcessManager:
    """Coordinates process launch, reconcile, logs, and stop operations."""

    def __init__(self, cfg: AppConfig, guard: PathGuard, store: ProcessStore) -> None:
        self._guard = guard
        self._store = store
        self._jobs_dir = Path(cfg.state.db_path).resolve().parent / "process_jobs"
        self._projects_root = resolve_projects_root(cfg)
        self._package_root = Path(__file__).resolve().parents[1]
        self._default_profile = cfg.nextflow.default_profile
        self._igenomes_ignore = cfg.nextflow.igenomes_ignore
        self._expose_pipeline_materials = cfg.nextflow.expose_pipeline_materials
        self._pipeline_catalog = (
            NextflowPipelineCatalog(cfg.nextflow.pipeline_roots, guard)
            if cfg.nextflow.pipeline_roots
            else None
        )
        self._jobs_dir.mkdir(parents=True, exist_ok=True)
        self._projects_root.mkdir(parents=True, exist_ok=True)

    def reconcile_all(self) -> None:
        """Reconcile all known process records."""
        for record in self._store.list_processes():
            self.reconcile(record.process_id)

    def _igenomes_ignore_config_path(self) -> Path:
        """Write and return the config file that disables iGenomes for this server.

        The settings are constants, so a single server-owned file is enough. It
        lives beside the process store rather than inside a run directory,
        because run and job directories are created with exist_ok=False at
        launch time and would collide with a file written during prepare.
        """
        path = self._jobs_dir.parent / IGENOMES_IGNORE_CONFIG_NAME
        path.write_text(IGENOMES_IGNORE_CONFIG, encoding="utf-8")
        return path

    def run_process(
        self,
        *,
        argv: list[str],
        cwd: str,
        env: dict[str, str] | None = None,
        stdin: str | None = None,
        detach: bool = True,
        timeout_seconds: float | None = None,
        label: str | None = None,
        kind: str = "command",
    ) -> dict[str, Any]:
        """Launch a process through the local runner."""
        normalized_argv = _normalize_argv(argv)
        normalized_env = _normalize_env(env)
        if timeout_seconds is not None and timeout_seconds <= 0:
            raise ValueError("timeout_seconds must be positive")

        resolved_cwd = self._guard.resolve_write(cwd)
        if resolved_cwd.is_symlink():
            raise ValueError(f"Refusing to run in symlink cwd: {resolved_cwd}")
        return self._launch_prepared_process(
            argv=normalized_argv,
            cwd=resolved_cwd,
            env=normalized_env,
            stdin=stdin,
            detach=detach,
            timeout_seconds=timeout_seconds,
            label=label,
            kind=kind,
        )

    def run_nextflow(
        self,
        *,
        executable: str,
        pipeline: str,
        cwd: str,
        entry: str | None = None,
        params: dict[str, Any] | None = None,
        profile: str | None = None,
        config_files: list[str] | None = None,
        work_dir: str | None = None,
        resume: bool = False,
        resume_session_id: str | None = None,
        extra_args: list[str] | None = None,
        env: dict[str, str] | None = None,
        detach: bool = True,
        label: str | None = None,
        prepare: bool = False,
        validate_params_schema: bool = False,
    ) -> dict[str, Any]:
        """Build and launch a Nextflow command using the standard process model."""
        prepared = self._prepare_nextflow_run(
            executable=executable,
            pipeline=pipeline,
            cwd=cwd,
            entry=entry,
            params=params,
            profile=profile,
            config_files=config_files,
            work_dir=work_dir,
            resume=resume,
            resume_session_id=resume_session_id,
            extra_args=extra_args,
            env=env,
            validate_params_schema=validate_params_schema,
        )

        if prepare:
            response = {
                "kind": "nextflow",
                "mode": "prepare",
                "label": label,
                "cwd": str(prepared.cwd),
                "path_checks": prepared.path_checks,
                "path_warnings": prepared.path_warnings,
                "resume_hint": prepared.resume_hint,
                "expected_artifacts": prepared.expected_artifacts,
                **prepared.command_extra,
            }
            if prepared.schema_validation is not None:
                response["schema_validation"] = prepared.schema_validation
            return response

        record = self._launch_prepared_process(
            argv=prepared.argv,
            cwd=prepared.cwd,
            env=prepared.env,
            stdin=None,
            detach=detach,
            timeout_seconds=None,
            label=label,
            kind="nextflow",
            job_paths=prepared.job_paths,
            command_extra=prepared.command_extra,
            command_metadata={"pipeline_fingerprint": prepared.pipeline_fingerprint},
        )
        result = _render_process_payload(record, detail="summary")
        if prepared.schema_validation is not None:
            result["schema_validation"] = prepared.schema_validation
        return result

    def _prepare_nextflow_run(
        self,
        *,
        executable: str,
        pipeline: str,
        cwd: str,
        path_base: str | None = None,
        entry: str | None,
        params: dict[str, Any] | None,
        profile: str | None,
        config_files: list[str] | None,
        work_dir: str | None,
        resume: bool,
        resume_session_id: str | None,
        extra_args: list[str] | None,
        env: dict[str, str] | None,
        validate_params_schema: bool,
        job_paths: JobPaths | None = None,
        default_results_dir: str | None = None,
        project_id: str | None = None,
        run_id: str | None = None,
    ) -> PreparedNextflowRun:
        """Normalize one Nextflow launch request without starting the runner."""
        resolved_cwd = self._guard.resolve_write(cwd)
        if resolved_cwd.is_symlink():
            raise ValueError(f"Refusing to run in symlink cwd: {resolved_cwd}")
        resolved_path_base = self._guard.resolve_write(path_base or cwd)

        raw_params = dict(params or {})
        if self._igenomes_ignore:
            # Ignore user-provided igenomes settings before generic path resolution.
            raw_params.pop("igenomes_ignore", None)
            raw_params.pop("igenomes_base", None)
        normalized_env = _normalize_env(env)
        normalized_extra_args = _normalize_string_list(extra_args or [], field="extra_args")
        pipeline_value, local_pipeline = self._resolve_pipeline_launch_target(
            pipeline,
            resolved_path_base,
        )
        raw_params = _bind_primary_results_dir_param(
            raw_params,
            default_results_dir=default_results_dir,
            local_pipeline=local_pipeline,
        )
        normalized_params = _normalize_nextflow_params(raw_params)
        normalized_params = _resolve_nextflow_param_values(
            self._guard,
            params=normalized_params,
            cwd=resolved_path_base,
        )
        effective_profile = profile if profile is not None else self._default_profile
        resolved_config_files = [
            str(self._resolve_read_or_pipeline_path(config_path, str(resolved_path_base)))
            for config_path in (config_files or [])
        ]
        if self._igenomes_ignore:
            resolved_config_files.append(str(self._igenomes_ignore_config_path()))
        resolved_work_dir, work_dir_source = _resolve_nextflow_work_dir(
            self._guard,
            cwd=resolved_cwd,
            work_dir=work_dir,
        )
        job_paths = job_paths or get_job_paths(self._jobs_dir / _new_process_id())
        run_layout, layout_warnings = _build_run_layout(
            run_root=resolved_cwd,
            work_dir=resolved_work_dir,
            work_dir_source=work_dir_source,
            params=normalized_params,
            job_dir=job_paths.job_dir,
            reserved_results_dir=default_results_dir,
        )
        nextflow_argv = _build_nextflow_argv(
            executable=executable,
            nextflow_log=str(job_paths.nextflow_log),
            pipeline=pipeline_value,
            entry=entry,
            params=normalized_params,
            profile=effective_profile,
            config_files=resolved_config_files,
            work_dir=resolved_work_dir,
            resume=resume,
            resume_session_id=resume_session_id,
            extra_args=normalized_extra_args,
        )

        schema_validation = None
        if validate_params_schema:
            schema_validation = self._validate_nextflow_params_schema(
                local_pipeline=local_pipeline,
                params=raw_params,
                profile=effective_profile,
                config_files=resolved_config_files,
                extra_args=normalized_extra_args,
            )

        path_checks = self._build_nextflow_param_path_checks(
            params=normalized_params,
            cwd=resolved_path_base,
        )
        path_warnings = _path_check_warnings(path_checks)

        pipeline_public = (
            pipeline_value if self._expose_pipeline_materials else _public_pipeline_value(pipeline)
        )
        command_extra = {
            "project": project_id,
            "run_id": run_id,
            "pipeline": pipeline_value,
            "pipeline_public": pipeline_public,
            "entry": entry,
            "profile": effective_profile,
            "config_files": resolved_config_files,
            "work_dir": resolved_work_dir,
            "resume": resume,
            "resume_session_id": resume_session_id,
            "params": normalized_params,
            "extra_args": normalized_extra_args,
            "run_layout": run_layout,
            "layout_warnings": layout_warnings,
        }
        expected_artifacts = _build_nextflow_expected_artifacts(
            cwd=resolved_cwd,
            job_paths=job_paths,
            command_extra=command_extra,
            launched=False,
            include_runtime_items=False,
        )
        resume_hint = self._build_nextflow_resume_hint(
            project_id=project_id,
            pipeline=pipeline_value,
            cwd=resolved_cwd,
            work_dir=resolved_work_dir,
            resume=resume,
            resume_session_id=resume_session_id,
        )

        return PreparedNextflowRun(
            argv=nextflow_argv,
            cwd=resolved_cwd,
            env=dict(normalized_env),
            job_paths=job_paths,
            command_extra=command_extra,
            pipeline_fingerprint=_build_nextflow_pipeline_fingerprint(
                pipeline=pipeline_value,
                local_pipeline=local_pipeline,
                expose_materials=self._expose_pipeline_materials,
                public_target=pipeline_public,
            ),
            schema_validation=schema_validation,
            path_checks=path_checks,
            path_warnings=path_warnings,
            resume_hint=resume_hint,
            expected_artifacts=expected_artifacts,
        )

    def _build_nextflow_param_path_checks(
        self,
        *,
        params: dict[str, Any],
        cwd: Path,
    ) -> list[dict[str, Any]]:
        """Build generic read/write path checks from CLI params."""
        checks: list[dict[str, Any]] = []
        for key, value in params.items():
            if not isinstance(value, str) or not value:
                continue

            role = _classify_nextflow_param_path_role(key, value)
            if role is None:
                continue

            if _is_remote_uri(value):
                checks.append(
                    {
                        "param": key,
                        "value": value,
                        "role": role,
                        "path": value,
                        "allowed": True,
                        "exists": True,
                        "parent_exists": True,
                        "check": "remote_uri",
                        "message": _render_remote_reference_check_message(
                            key=key,
                            role=role,
                            value=value,
                        ),
                    }
                )
                continue

            resolved = _resolve_candidate_path(value, cwd)
            allowed = _is_allowed_path(self._guard, resolved, role=role)
            exists = resolved.exists()
            parent_exists = resolved.parent.exists()
            checks.append(
                {
                    "param": key,
                    "value": value,
                    "role": role,
                    "path": str(resolved),
                    "allowed": allowed,
                    "exists": exists,
                    "parent_exists": parent_exists,
                    "message": _render_path_check_message(
                        key=key,
                        role=role,
                        path=resolved,
                        allowed=allowed,
                        exists=exists,
                    ),
                }
            )
        return checks

    def _build_nextflow_resume_hint(
        self,
        *,
        project_id: str | None,
        pipeline: str,
        cwd: Path,
        work_dir: str | None,
        resume: bool,
        resume_session_id: str | None,
    ) -> dict[str, Any]:
        """Build a compact resume hint from previous matching Nextflow runs."""
        requested = bool(resume or resume_session_id)
        same_project_runs: list[dict[str, Any]] = []
        for record in self._store.list_processes():
            if record.kind != "nextflow" or record.status == "running":
                continue
            payload = _record_to_dict(record)
            if payload.get("pipeline") != pipeline:
                continue
            if project_id is not None and payload.get("project") != project_id:
                continue
            payload["resume_candidate_compatible"] = _is_resume_candidate_compatible(payload)
            same_project_runs.append(payload)

        same_project_runs.sort(key=lambda item: str(item.get("finished_at") or ""), reverse=True)

        source_run: dict[str, Any] | None = None
        if resume_session_id is not None:
            for payload in same_project_runs:
                if payload.get("nextflow_session_uuid") == resume_session_id:
                    source_run = payload
                    break
        elif requested and same_project_runs:
            source_run = same_project_runs[0]

        candidates: list[dict[str, Any]] = []
        for payload in same_project_runs:
            if not bool(payload.get("resume_candidate_compatible", False)):
                continue
            if payload.get("cwd") != str(cwd):
                continue
            if payload.get("work_dir") != work_dir:
                continue
            candidates.append(
                {
                    "run_id": payload.get("run_id"),
                    "process_id": payload["process_id"],
                    "status": payload["status"],
                    "finished_at": payload["finished_at"],
                    "run_root": payload.get("cwd"),
                    "work_dir": payload.get("work_dir"),
                    "nextflow_session_uuid": payload.get("nextflow_session_uuid"),
                }
            )

        can_try_resume = bool(candidates)
        resume_incompatible_reason = None
        suggested_run_id = None
        suggested_run_root = None
        suggested_work_dir = None
        if requested and source_run is not None and not can_try_resume:
            suggested_run_id = source_run.get("run_id")
            suggested_run_root = source_run.get("cwd")
            suggested_work_dir = source_run.get("work_dir")
            if not bool(source_run.get("resume_candidate_compatible", False)):
                resume_incompatible_reason = (
                    "The source run does not currently expose a usable Nextflow session UUID, "
                    "run root, or work directory for resume."
                )
            elif source_run.get("cwd") != str(cwd) or source_run.get("work_dir") != work_dir:
                resume_incompatible_reason = (
                    "Resume in the current project layout requires the original run root and "
                    "work directory. Reuse the source run_id or keep the original work_dir."
                )

        return {
            "requested": requested,
            "resume_session_id": resume_session_id,
            "resume_requires_same_run_root": requested,
            "resume_requires_same_work_dir": requested,
            "can_try_resume": can_try_resume,
            "candidate_count": len(candidates),
            "candidates": candidates[:3],
            "source_run_id": None if source_run is None else source_run.get("run_id"),
            "source_run_root": None if source_run is None else source_run.get("cwd"),
            "source_work_dir": None if source_run is None else source_run.get("work_dir"),
            "source_process_id": None if source_run is None else source_run.get("process_id"),
            "source_nextflow_session_uuid": (
                None if source_run is None else source_run.get("nextflow_session_uuid")
            ),
            "resume_incompatible_reason": resume_incompatible_reason,
            "suggested_run_id": suggested_run_id,
            "suggested_run_root": suggested_run_root,
            "suggested_work_dir": suggested_work_dir,
        }

    def _resolve_pipeline_launch_target(
        self,
        pipeline: str,
        resolved_cwd: Path,
    ) -> tuple[str, LocalPipeline | None]:
        """Resolve the launch target and optional local pipeline metadata."""
        if not pipeline:
            raise ValueError("pipeline must be a non-empty string")

        pipeline_path = Path(pipeline)
        if pipeline_path.is_absolute():
            resolved_path = self._resolve_read_or_pipeline_path(pipeline)
            return str(resolved_path), _local_pipeline_for_path(resolved_path)

        if pipeline.startswith(".") or (resolved_cwd / pipeline).exists():
            resolved_path = self._resolve_read_or_pipeline_path(pipeline, str(resolved_cwd))
            return str(resolved_path), _local_pipeline_for_path(resolved_path)

        if self._pipeline_catalog is not None and "/" not in pipeline:
            try:
                local_pipeline = self._pipeline_catalog.resolve_pipeline(pipeline)
            except ResourceNotFoundError:
                pass
            else:
                return str(local_pipeline.main_script), local_pipeline

        return pipeline, None

    def _resolve_read_or_pipeline_path(self, path: str, cwd: str | None = None) -> Path:
        """Resolve a read path from generic roots or configured pipeline roots."""
        try:
            return self._guard.resolve_read(path, cwd)
        except PermissionError as read_error:
            if self._pipeline_catalog is None:
                raise read_error
            try:
                return self._pipeline_catalog.resolve_path(path, cwd)
            except PermissionError:
                raise read_error

    def _validate_nextflow_params_schema(
        self,
        *,
        local_pipeline: LocalPipeline | None,
        params: dict[str, Any],
        profile: str | None,
        config_files: list[str],
        extra_args: list[str],
    ) -> dict[str, Any]:
        """Validate CLI params against a local nextflow_schema.json when available."""
        if local_pipeline is None or local_pipeline.schema_path is None:
            raise ValueError(
                "validate_params_schema requires a local pipeline with nextflow_schema.json"
            )

        schema = read_schema_payload(local_pipeline.schema_path)
        if schema is None:
            raise ValueError(
                "validate_params_schema requires a local pipeline with nextflow_schema.json"
            )

        allow_external_required = bool(
            profile or config_files or _extra_args_include_params_file(extra_args)
        )
        report = validate_nextflow_params_against_schema(
            schema=schema,
            params=params,
            allow_missing_required_from_external_sources=allow_external_required,
        )
        if report["errors"]:
            raise ValueError(_summarize_nextflow_schema_errors(report["errors"]))

        notes: list[str] = []
        if allow_external_required:
            notes.append(
                "Required-field checks only covered CLI params plus schema defaults; config "
                "files, profiles, or params files may still provide missing values."
            )
        return {
            "schema_path": str(local_pipeline.schema_path),
            **report,
            "notes": notes,
        }

    def _launch_prepared_process(
        self,
        *,
        argv: list[str],
        cwd: Path,
        env: dict[str, str],
        stdin: str | None,
        detach: bool,
        timeout_seconds: float | None,
        label: str | None,
        kind: str,
        job_paths: JobPaths | None = None,
        process_id: str | None = None,
        command_extra: dict[str, Any] | None = None,
        command_metadata: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """Persist command metadata and start the detached runner."""
        process_id = process_id or (
            job_paths.job_dir.name if job_paths is not None else _new_process_id()
        )
        created_at = _utcnow()
        prepared_job_paths = job_paths or get_job_paths(self._jobs_dir / process_id)
        prepared_job_paths.job_dir.mkdir(parents=True, exist_ok=False)

        command_payload = {
            "process_id": process_id,
            "kind": kind,
            "label": label,
            "argv": argv,
            "cwd": str(cwd),
            "env": env,
            "stdin": stdin,
            "timeout_seconds": timeout_seconds,
            "created_at": created_at,
        }
        if command_extra:
            command_payload.update(command_extra)
        if command_metadata:
            command_payload.update(command_metadata)

        write_json(prepared_job_paths.command_json, command_payload)
        self._store.create_process(
            process_id=process_id,
            kind=kind,
            label=label,
            cwd=str(cwd),
            argv=argv,
            job_dir=str(prepared_job_paths.job_dir),
            created_at=created_at,
        )

        runner_env = os.environ.copy()
        runner_env["PYTHONPATH"] = _prepend_pythonpath(
            runner_env.get("PYTHONPATH"),
            str(self._package_root),
        )

        runner = subprocess.Popen(
            [sys.executable, "-m", "nextmcp.runner", str(prepared_job_paths.job_dir)],
            env=runner_env,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
        self._store.set_runner_pid(process_id, runner.pid, updated_at=_utcnow())

        if not detach:
            runner.wait()
            return self.reconcile(process_id)

        return self.reconcile(process_id)

    def get_process(
        self,
        process_id: str,
        *,
        include: Sequence[str] | None = None,
        detail: str = "summary",
    ) -> dict[str, Any]:
        """Return current process metadata."""
        record = self.reconcile(process_id)
        requested_sections = sorted(set(include or []))
        payload = _render_process_payload(record, detail=detail)
        payload["detail"] = detail
        if not requested_sections:
            return payload

        job_paths = get_job_paths(Path(record["job_dir"]))
        payload["includes"] = requested_sections

        diagnosis: dict[str, Any] | None = None
        if "progress" in requested_sections:
            payload["progress"] = _build_process_progress(record, job_paths)
        if "artifact_summary" in requested_sections:
            payload["artifact_summary"] = _build_process_artifact_summary(
                record,
                job_paths,
                self._store,
            )
        if "diagnosis" in requested_sections or "next_actions" in requested_sections:
            diagnosis = _build_process_diagnosis(record, job_paths)
        if "diagnosis" in requested_sections and diagnosis is not None:
            payload["diagnosis"] = diagnosis
        if "next_actions" in requested_sections:
            payload["next_actions"] = _build_process_next_actions(record, diagnosis)
        return payload

    def get_process_artifacts(
        self,
        process_id: str,
        *,
        section: str,
        root_label: str | None = None,
        path_contains: str | None = None,
        limit: int = DEFAULT_PROCESS_ARTIFACT_LIMIT,
        offset: int = 0,
        detail: str = "auto",
    ) -> dict[str, Any]:
        """List one artifact section for a process with pagination."""
        if limit < 0:
            raise ValueError("limit must be >= 0")
        if limit > MAX_PROCESS_ARTIFACT_LIMIT:
            raise ValueError(f"limit must be <= {MAX_PROCESS_ARTIFACT_LIMIT}")
        if offset < 0:
            raise ValueError("offset must be >= 0")
        if root_label is not None and section != "items":
            raise ValueError("root_label is only supported when section='items'")

        record = self.reconcile(process_id)
        job_paths = get_job_paths(Path(record["job_dir"]))
        return _list_process_artifact_section(
            record,
            job_paths,
            self._store,
            section=section,
            root_label=root_label,
            path_contains=path_contains,
            limit=limit,
            offset=offset,
            detail=detail,
        )

    def list_processes(
        self,
        *,
        status: str | None = None,
        kind: str | None = None,
        pipeline: str | None = None,
        entry: str | None = None,
        label_contains: str | None = None,
        artifact_path_contains: str | None = None,
        finished_after: str | None = None,
        finished_before: str | None = None,
        limit: int = 100,
        offset: int = 0,
        detail: str = "summary",
    ) -> dict[str, Any]:
        """List processes after reconciling persisted state."""
        source_records = self._store.list_processes()
        if artifact_path_contains is not None:
            matched_ids = set(
                self._store.find_process_ids_by_artifact_path_contains(artifact_path_contains)
            )
            if not matched_ids:
                self._backfill_artifact_index()
                matched_ids = set(
                    self._store.find_process_ids_by_artifact_path_contains(artifact_path_contains)
                )
            source_records = [
                record for record in source_records if record.process_id in matched_ids
            ]

        records = [self.reconcile(record.process_id) for record in source_records]
        filtered = [
            record
            for record in records
            if (status is None or record["status"] == status)
            and (kind is None or record["kind"] == kind)
            and (pipeline is None or record.get("pipeline") == pipeline)
            and (entry is None or record.get("entry") == entry)
            and (
                label_contains is None
                or (isinstance(record.get("label"), str) and label_contains in record["label"])
            )
            and _matches_finished_window(
                record,
                finished_after=finished_after,
                finished_before=finished_before,
            )
        ]
        sliced = filtered[offset : offset + limit]
        return {
            "detail": detail,
            "count": len(sliced),
            "total": len(filtered),
            "processes": [_render_process_payload(record, detail=detail) for record in sliced],
        }

    def _backfill_artifact_index(self) -> None:
        """Backfill artifact-path index entries from existing terminal Nextflow runs."""
        for stored in self._store.list_processes():
            if stored.kind != "nextflow" or stored.status == "running":
                continue
            payload = _record_to_dict(stored)
            job_paths = get_job_paths(Path(stored.job_dir))
            _maybe_write_nextflow_artifacts_manifest(payload, job_paths, self._store)

    def read_logs(
        self,
        process_id: str,
        *,
        stream: str = "stdout",
        view: Literal["raw", "important"] = "raw",
        after_line: int | None = None,
        start_line: int | None = None,
        end_line: int | None = None,
        tail: int | None = DEFAULT_PROCESS_LOG_TAIL,
    ) -> dict[str, Any]:
        """Read process logs with line slicing."""
        if view not in {"raw", "important"}:
            raise ValueError("view must be 'raw' or 'important'")
        if after_line is not None:
            if after_line < 0:
                raise ValueError("after_line must be >= 0")
            if start_line is not None or end_line is not None:
                raise ValueError("after_line cannot be combined with start_line or end_line")
        if start_line is not None and start_line < 1:
            raise ValueError("start_line must be >= 1")
        if end_line is not None and end_line < 1:
            raise ValueError("end_line must be >= 1")
        if tail is not None and tail < 0:
            raise ValueError("tail must be >= 0 or null")

        record = self.reconcile(process_id)
        paths = get_job_paths(Path(record["job_dir"]))
        if view == "important":
            return _build_important_log_payload(record, paths, stream=stream)

        log_path = _log_path_for_stream(record, paths, stream)

        if not log_path.exists():
            return {
                "process_id": process_id,
                "stream": stream,
                "view": "raw",
                "path": str(log_path),
                "total_lines": 0,
                "returned_start_line": None,
                "returned_end_line": None,
                "returned_line_count": 0,
                "next_after_line": 0,
                "content": "",
            }

        total_lines, lines, returned_start_line, returned_end_line = _read_log_slice(
            log_path,
            after_line=after_line,
            start_line=start_line,
            end_line=end_line,
            tail=tail,
        )

        return {
            "process_id": process_id,
            "stream": stream,
            "view": "raw",
            "path": str(log_path),
            "total_lines": total_lines,
            "returned_start_line": returned_start_line,
            "returned_end_line": returned_end_line,
            "returned_line_count": len(lines),
            "next_after_line": total_lines,
            "content": "".join(lines),
        }

    def stop_process(self, process_id: str, *, force: bool = False) -> dict[str, Any]:
        """Request process termination and reconcile final state."""
        record = self.reconcile(process_id)
        if record["status"] != "running":
            return {
                "process_id": process_id,
                "requested": False,
                "status": record["status"],
            }

        paths = get_job_paths(Path(record["job_dir"]))
        write_json(
            paths.stop_json,
            {
                "requested_at": _utcnow(),
                "force": force,
            },
        )
        self._store.mark_stop_requested(process_id, updated_at=_utcnow())

        target_pid = record["pid"]
        target_pgid = record["pgid"]
        runner_pid = record["runner_pid"]

        if target_pgid is not None or target_pid is not None:
            _terminate_process_group(
                target_pgid,
                target_pid,
                force=force,
                grace_seconds=DEFAULT_STOP_GRACE_SECONDS,
            )
        elif runner_pid is not None and _is_pid_alive(runner_pid):
            try:
                os.kill(runner_pid, signal.SIGKILL if force else signal.SIGTERM)
            except ProcessLookupError:
                pass

        _wait_for_completion(paths.result_json, timeout_seconds=DEFAULT_STOP_GRACE_SECONDS)
        record = self.reconcile(process_id)
        return {
            "process_id": process_id,
            "requested": True,
            "status": record["status"],
            "force": force,
        }

    def delete_process(self, process_id: str) -> dict[str, Any]:
        """Delete a terminal process record and its job directory."""
        record = self.reconcile(process_id)
        if record["status"] == "running":
            raise ValueError("Cannot delete a running process; stop it first")

        job_dir = Path(record["job_dir"])
        if job_dir.is_symlink():
            raise ValueError(f"Refusing to delete symlink job_dir: {job_dir}")
        if job_dir.exists():
            if not job_dir.is_dir():
                raise NotADirectoryError(f"Expected process job_dir to be a directory: {job_dir}")
            shutil.rmtree(job_dir)

        self._store.delete_process(process_id)
        return {
            "process_id": process_id,
            "deleted": True,
            "status": record["status"],
            "job_dir": str(job_dir),
        }

    def reconcile(self, process_id: str) -> dict[str, Any]:
        """Reconcile stored state with job files and process liveness."""
        record = self._store.get_process(process_id)
        if record is None:
            raise ResourceNotFoundError(
                resource_type="process",
                resource_id=process_id,
                message=f"Unknown process_id: {process_id}",
            )

        paths = get_job_paths(Path(record.job_dir))
        result = read_process_state_json(paths.result_json)
        if result is not None:
            self._store.set_result(
                process_id,
                status=str(result["status"]),
                exit_code=_optional_int(result.get("exit_code")),
                finished_at=str(result["finished_at"]),
                timed_out=bool(result.get("timed_out", False)),
                updated_at=_utcnow(),
            )
            record = _require_record(self._store.get_process(process_id), process_id)
            payload = _record_to_dict(record)
            _maybe_write_nextflow_artifacts_manifest(payload, paths, self._store)
            return payload

        runtime = read_process_state_json(paths.runtime_json)
        if runtime is not None:
            self._store.set_runtime(
                process_id,
                pid=_optional_int(runtime.get("pid")),
                pgid=_optional_int(runtime.get("pgid")),
                started_at=_optional_str(runtime.get("started_at")),
                updated_at=_utcnow(),
            )
            record = _require_record(self._store.get_process(process_id), process_id)

        if record.status != "running":
            payload = _record_to_dict(record)
            _maybe_write_nextflow_artifacts_manifest(payload, paths, self._store)
            return payload

        stop_requested = paths.stop_json.exists() or record.stop_requested
        child_alive = _is_process_group_alive(record.pgid) or _is_pid_alive(record.pid)
        runner_alive = _is_pid_alive(record.runner_pid)
        if child_alive or runner_alive:
            return _record_to_dict(record)

        terminal_status = "stopped" if stop_requested else "failed"
        self._store.set_result(
            process_id,
            status=terminal_status,
            exit_code=record.exit_code,
            finished_at=_utcnow(),
            timed_out=record.timed_out,
            updated_at=_utcnow(),
        )
        record = _require_record(self._store.get_process(process_id), process_id)
        payload = _record_to_dict(record)
        _maybe_write_nextflow_artifacts_manifest(payload, paths, self._store)
        return payload


def get_job_paths(job_dir: Path) -> JobPaths:
    """Build standard job directory paths."""
    return JobPaths(
        job_dir=job_dir,
        command_json=job_dir / "command.json",
        runtime_json=job_dir / "runtime.json",
        result_json=job_dir / "result.json",
        stop_json=job_dir / "stop.json",
        stdout_log=job_dir / "stdout.log",
        stderr_log=job_dir / "stderr.log",
        nextflow_log=job_dir / "nextflow.log",
        artifacts_json=job_dir / "artifacts.json",
    )


def read_json(path: Path) -> dict[str, Any] | None:
    """Read a JSON file if it exists."""
    if not path.exists():
        return None
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"Expected JSON object in {path}")
    return payload


def read_process_state_json(path: Path) -> dict[str, Any] | None:
    """Read optional process state JSON without failing startup on stale bad files."""
    try:
        return read_json(path)
    except (json.JSONDecodeError, ValueError) as exc:
        logger.warning("Ignoring invalid process state JSON at %s: %s", path, exc)
        return None


def write_json(path: Path, payload: dict[str, Any]) -> None:
    """Atomically write JSON to disk."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = path.with_name(f"{path.name}.tmp")
    tmp_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    tmp_path.replace(path)


def _new_process_id() -> str:
    """Generate a unique process identifier."""
    return f"proc_{uuid.uuid4().hex}"


def _utcnow() -> str:
    """Return an ISO8601 UTC timestamp."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def _is_pid_alive(pid: int | None) -> bool:
    """Check whether a process exists."""
    if pid is None:
        return False
    proc_state = _read_proc_state(pid)
    if proc_state is not None:
        return proc_state != "Z"
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def _is_process_group_alive(pgid: int | None) -> bool:
    """Check whether a process group exists."""
    if pgid is None:
        return False
    group_state = _read_proc_group_state(pgid)
    if group_state is not None:
        return group_state
    try:
        os.killpg(pgid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def _terminate_process_group(
    pgid: int | None,
    pid: int | None,
    *,
    force: bool,
    grace_seconds: float,
) -> None:
    """Terminate the child process group, with TERM then KILL by default."""
    target_signal = signal.SIGKILL if force else signal.SIGTERM
    _send_signal(pgid, pid, target_signal)
    if force:
        return

    deadline = time.monotonic() + grace_seconds
    while time.monotonic() < deadline:
        if not _is_process_group_alive(pgid) and not _is_pid_alive(pid):
            return
        time.sleep(0.1)
    _send_signal(pgid, pid, signal.SIGKILL)


def _send_signal(pgid: int | None, pid: int | None, sig: signal.Signals) -> None:
    """Send a signal to a process group or a fallback single PID."""
    try:
        if pgid is not None:
            os.killpg(pgid, sig)
        elif pid is not None:
            os.kill(pid, sig)
    except ProcessLookupError:
        return


def _wait_for_completion(result_json: Path, *, timeout_seconds: float) -> None:
    """Wait briefly for result.json to appear."""
    deadline = time.monotonic() + timeout_seconds
    while time.monotonic() < deadline:
        if result_json.exists():
            return
        time.sleep(0.1)


def _read_proc_state(pid: int) -> str | None:
    """Read one process state from `/proc/<pid>/stat` when available."""
    stat_fields = _read_proc_stat_fields(pid)
    if stat_fields is None:
        return None
    return stat_fields[0]


def _read_proc_group_state(pgid: int) -> bool | None:
    """Return whether one process group has any non-zombie member."""
    proc_root = Path("/proc")
    if not proc_root.is_dir():
        return None

    saw_member = False
    try:
        entries = list(proc_root.iterdir())
    except OSError:
        return None

    for entry in entries:
        if not entry.name.isdigit():
            continue
        stat_fields = _read_proc_stat_fields(int(entry.name))
        if stat_fields is None:
            continue
        proc_pgid = _read_proc_group_id(stat_fields)
        if proc_pgid != pgid:
            continue
        saw_member = True
        if stat_fields[0] != "Z":
            return True

    if saw_member:
        return False
    return None


def _read_proc_group_id(stat_fields: list[str]) -> int | None:
    """Read process group id from parsed `/proc/<pid>/stat` fields."""
    if len(stat_fields) < 3:
        return None
    try:
        return int(stat_fields[2])
    except ValueError:
        return None


def _read_proc_stat_fields(pid: int) -> list[str] | None:
    """Parse `/proc/<pid>/stat` fields after the process name."""
    stat_path = Path("/proc") / str(pid) / "stat"
    try:
        content = stat_path.read_text(encoding="utf-8")
    except OSError:
        return None

    closing_paren = content.rfind(")")
    if closing_paren < 0:
        return None
    suffix = content[closing_paren + 2 :].strip()
    if not suffix:
        return None
    return suffix.split()


def _normalize_argv(argv: list[str]) -> list[str]:
    """Validate and normalize argv input."""
    if not argv:
        raise ValueError("argv must be a non-empty list of strings")
    normalized: list[str] = []
    for item in argv:
        if not isinstance(item, str) or not item:
            raise ValueError("argv must be a non-empty list of strings")
        normalized.append(item)
    return normalized


def _normalize_env(env: dict[str, str] | None) -> dict[str, str]:
    """Validate environment overrides."""
    if env is None:
        return {}
    normalized: dict[str, str] = {}
    for key, value in env.items():
        if not key:
            raise ValueError("env keys must be non-empty strings")
        normalized[str(key)] = str(value)
    return normalized


def _record_to_dict(record: ProcessRecord) -> dict[str, Any]:
    """Convert a ProcessRecord into tool output."""
    job_paths = get_job_paths(Path(record.job_dir))
    payload = {
        "process_id": record.process_id,
        "kind": record.kind,
        "label": record.label,
        "status": record.status,
        "cwd": record.cwd,
        "argv": record.argv,
        "job_dir": record.job_dir,
        "created_at": record.created_at,
        "updated_at": record.updated_at,
        "started_at": record.started_at,
        "finished_at": record.finished_at,
        "runner_pid": record.runner_pid,
        "pid": record.pid,
        "pgid": record.pgid,
        "exit_code": record.exit_code,
        "timed_out": record.timed_out,
        "stop_requested": record.stop_requested,
        "stdout_log": str(job_paths.stdout_log),
        "stderr_log": str(job_paths.stderr_log),
    }
    if record.kind == "nextflow":
        payload.update(_read_nextflow_launch_metadata(job_paths.command_json))
        payload["nextflow_log"] = str(job_paths.nextflow_log)
        payload["nextflow_session_uuid"] = _extract_nextflow_session_uuid(job_paths.nextflow_log)
    return payload


def _render_process_payload(
    record: dict[str, Any],
    *,
    detail: str,
) -> dict[str, Any]:
    """Render one process payload in summary or full form."""
    if detail == "full":
        payload = dict(record)
        if record["kind"] == "nextflow":
            payload["pipeline"] = record.get("pipeline_public", record.get("pipeline"))
        return payload
    if detail != "summary":
        raise ValueError("detail must be 'summary' or 'full'")

    payload = {
        "process_id": record["process_id"],
        "kind": record["kind"],
        "label": record.get("label"),
        "status": record["status"],
        "exit_code": record.get("exit_code"),
        "timed_out": bool(record.get("timed_out", False)),
        "stop_requested": bool(record.get("stop_requested", False)),
        "created_at": record.get("created_at"),
        "updated_at": record.get("updated_at"),
        "started_at": record.get("started_at"),
        "finished_at": record.get("finished_at"),
    }
    if record["kind"] == "nextflow":
        payload.update(
            {
                "project": record.get("project"),
                "run_id": record.get("run_id"),
                "pipeline": record.get("pipeline_public", record.get("pipeline")),
                "entry": record.get("entry"),
                "profile": record.get("profile"),
            }
        )
    return payload


