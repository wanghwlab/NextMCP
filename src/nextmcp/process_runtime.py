def _build_process_artifact_summary(
    record: dict[str, Any],
    job_paths: JobPaths,
    store: ProcessStore,
) -> dict[str, Any]:
    """Build a small artifact summary suitable for compact status views."""
    record_files = _build_process_record_files(record, job_paths)
    sections = ["record_files"]
    counts: dict[str, int] = {"record_files": len(record_files)}
    manifest_path = None
    manifest_available = False
    pipeline_fingerprint = None
    truncated = False

    if record["kind"] == "nextflow":
        declared_outputs = _build_declared_outputs(record, job_paths)
        manifest = _load_nextflow_artifacts_manifest(record, job_paths, store)
        sections.extend(["declared_outputs", "published_roots", "items"])
        counts["declared_outputs"] = len(declared_outputs)
        counts["published_roots"] = len(manifest["published_roots"]) if manifest is not None else 0
        counts["items"] = len(manifest["items"]) if manifest is not None else 0
        manifest_path = str(job_paths.artifacts_json)
        manifest_available = manifest is not None
        pipeline_fingerprint = (
            manifest["pipeline_fingerprint"]
            if manifest is not None
            else record.get("pipeline_fingerprint")
        )
        truncated = bool(manifest["limits"]["truncated"]) if manifest is not None else False

    return {
        "available": record["kind"] == "nextflow",
        "manifest_available": manifest_available,
        "manifest_path": manifest_path,
        "pipeline_fingerprint": pipeline_fingerprint,
        "sections": sections,
        "counts": counts,
        "truncated": truncated,
    }


def _list_process_artifact_section(
    record: dict[str, Any],
    job_paths: JobPaths,
    store: ProcessStore,
    *,
    section: str,
    root_label: str | None,
    path_contains: str | None,
    limit: int,
    offset: int,
    detail: str,
) -> dict[str, Any]:
    """List one artifact section with filtering and pagination."""
    valid_sections = {"record_files", "declared_outputs", "published_roots", "items"}
    if section not in valid_sections:
        raise ValueError(
            "section must be one of 'record_files', 'declared_outputs', "
            "'published_roots', or 'items'"
        )

    manifest_path = str(job_paths.artifacts_json) if record["kind"] == "nextflow" else None
    manifest_available = False
    truncated = False

    if section == "record_files":
        entries = _build_process_record_files(record, job_paths)
    elif section == "declared_outputs":
        if record["kind"] != "nextflow":
            raise StructuredToolError(
                error_code="artifact_section_unavailable",
                message="section 'declared_outputs' is only available for kind='nextflow'",
                suggestions=("Use section='record_files' for this process.",),
                details={"section": section, "kind": record["kind"]},
            )
        entries = _build_declared_outputs(record, job_paths)
    else:
        if record["kind"] != "nextflow":
            raise StructuredToolError(
                error_code="artifact_section_unavailable",
                message=f"section '{section}' is only available for kind='nextflow'",
                suggestions=("Use section='record_files' for this process.",),
                details={"section": section, "kind": record["kind"]},
            )
        manifest = _load_nextflow_artifacts_manifest(record, job_paths, store)
        manifest_available = manifest is not None
        if manifest is None:
            entries = []
        else:
            entries = list(manifest[section])
            truncated = bool(manifest["limits"]["truncated"])

    if root_label is not None:
        entries = [item for item in entries if root_label == _optional_str(item.get("root_label"))]
    if path_contains is not None:
        entries = [item for item in entries if _artifact_item_matches_path(item, path_contains)]

    total_count = len(entries)
    resolved_detail = _resolve_artifact_detail(section=section, detail=detail)
    paged_entries = [
        _render_artifact_item(item, section=section, detail=resolved_detail)
        for item in entries[offset : offset + limit]
    ]
    payload: dict[str, Any] = {
        "process_id": record["process_id"],
        "section": section,
        "detail": resolved_detail,
        "filters": _artifact_section_filters(
            root_label=root_label,
            path_contains=path_contains,
            limit=limit,
            offset=offset,
        ),
        "total_count": total_count,
        "returned_count": len(paged_entries),
        "has_more": offset + len(paged_entries) < total_count,
        "items": paged_entries,
    }
    if section in {"published_roots", "items"}:
        payload["manifest_available"] = manifest_available
        if manifest_available and manifest_path is not None:
            payload["manifest_path"] = manifest_path
    if section == "items":
        payload["truncated"] = truncated
    return payload


def _artifact_section_filters(
    *,
    root_label: str | None,
    path_contains: str | None,
    limit: int,
    offset: int,
) -> dict[str, Any]:
    """Build a compact filter payload without null-valued keys."""
    payload: dict[str, Any] = {
        "limit": limit,
        "offset": offset,
    }
    if root_label is not None:
        payload["root_label"] = root_label
    if path_contains is not None:
        payload["path_contains"] = path_contains
    return payload


def _resolve_artifact_detail(*, section: str, detail: str) -> Literal["compact", "full"]:
    """Resolve one requested artifact detail level."""
    if detail == "auto":
        return "compact" if section == "items" else "full"
    if detail in {"compact", "full"}:
        return cast(Literal["compact", "full"], detail)
    raise ValueError("detail must be 'auto', 'compact', or 'full'")


def _render_artifact_item(
    item: dict[str, Any],
    *,
    section: str,
    detail: Literal["compact", "full"],
) -> dict[str, Any]:
    """Render one artifact item at the requested detail level."""
    if detail == "full":
        return dict(item)

    if section == "items":
        return {
            "root_label": item.get("root_label"),
            "rel_path": item.get("rel_path"),
            "type": item.get("type"),
        }

    compact_keys = ("label", "kind", "when", "exists")
    return {key: item[key] for key in compact_keys if key in item}


def _artifact_item_matches_path(item: dict[str, Any], needle: str) -> bool:
    """Return whether one artifact descriptor mentions a path fragment."""
    for key in ("path", "rel_path", "label", "root_label"):
        value = item.get(key)
        if isinstance(value, str) and needle in value:
            return True
    return False


def _build_process_diagnosis(record: dict[str, Any], job_paths: JobPaths) -> dict[str, Any]:
    """Classify current process state into a compact agent-facing diagnosis."""
    status = str(record["status"])
    if status == "running":
        return {
            "category": "running",
            "summary": "Process is still running.",
            "retryable": False,
            "log_stream": "nextflow" if record["kind"] == "nextflow" else "stdout",
            "last_log_line": _diagnostic_last_line(record, job_paths),
        }
    if status == "succeeded":
        return {
            "category": "succeeded",
            "summary": "Process finished successfully.",
            "retryable": False,
            "log_stream": None,
            "last_log_line": _diagnostic_last_line(record, job_paths),
        }
    if status == "stopped":
        return {
            "category": "stopped",
            "summary": "Process was stopped before successful completion.",
            "retryable": True,
            "log_stream": None,
            "last_log_line": _diagnostic_last_line(record, job_paths),
        }
    if bool(record.get("timed_out")):
        return {
            "category": "timed_out",
            "summary": "Process hit its configured timeout.",
            "retryable": True,
            "log_stream": "stderr",
            "last_log_line": _diagnostic_last_line(record, job_paths),
        }

    diagnostic_stream, last_line = _failure_log_hint(record, job_paths)
    category = _classify_failure_category(last_line)
    return {
        "category": category,
        "summary": _failure_summary(category, last_line),
        "retryable": category in {"path_missing", "permission_denied", "resource_exhausted"},
        "log_stream": diagnostic_stream,
        "last_log_line": last_line,
    }


def _build_process_next_actions(
    record: dict[str, Any],
    diagnosis: dict[str, Any] | None,
) -> list[str]:
    """Suggest concise next actions without requiring extra tool types."""
    status = str(record["status"])
    if status == "running":
        return [
            "Poll the run status with progress until the status is terminal.",
            "Read raw appended log lines only when the compact status is not enough.",
        ]

    if status == "succeeded":
        if record["kind"] == "nextflow":
            return [
                "Inspect declared output paths first before broader filesystem scans.",
                "Inspect one artifact section at a time when you need details.",
            ]
        return ["Inspect stdout/stderr logs only if you need command output details."]

    category = diagnosis.get("category") if diagnosis is not None else None
    actions: list[str] = []
    if record["kind"] == "nextflow":
        actions.append("Read the Nextflow framework log first for the framework-level error.")
    else:
        actions.append("Read stderr first for the error output.")

    if category == "path_missing":
        actions.append("Fix the missing input path before retrying the run.")
    elif category == "permission_denied":
        actions.append(
            "Move inputs/outputs under allowed roots or adjust server permissions before retrying."
        )
    elif category == "resource_exhausted":
        actions.append(
            "Retry only after increasing available resources or reducing the requested workload."
        )
    elif status == "stopped":
        actions.append(
            "Decide whether the run should stay stopped or be relaunched from a clean command."
        )

    if record["kind"] == "nextflow" and status in {"failed", "stopped"}:
        actions.append(
            "If the work directory is still valid, prepare or rerun with "
            "`resume=true` to reuse cached work."
        )
    return actions


def _diagnostic_last_line(record: dict[str, Any], job_paths: JobPaths) -> str | None:
    """Return the last visible line from the preferred diagnostic stream."""
    _stream, last_line = _failure_log_hint(record, job_paths)
    return last_line


def _failure_log_hint(record: dict[str, Any], job_paths: JobPaths) -> tuple[str | None, str | None]:
    """Pick the best log stream and return its last visible line."""
    stream_candidates = ["stderr"]
    if record["kind"] == "nextflow":
        stream_candidates.insert(0, "nextflow")
    stream_candidates.append("stdout")

    for stream in stream_candidates:
        log_path = _log_path_for_stream(record, job_paths, stream)
        if not log_path.exists():
            continue
        _total, lines, _start, _end = _read_log_slice(
            log_path,
            after_line=None,
            start_line=None,
            end_line=None,
            tail=1,
        )
        if lines:
            return stream, lines[-1].rstrip("\n")
    return None, None


def _classify_failure_category(last_line: str | None) -> str:
    """Map one last-log-line hint into a generic failure category."""
    if last_line is None:
        return "process_failed"

    lowered = last_line.lower()
    if "permission denied" in lowered:
        return "permission_denied"
    if "no such file" in lowered or "not found" in lowered or "missing" in lowered:
        return "path_missing"
    if "unknown parameter" in lowered or "schema validation failed" in lowered:
        return "invalid_arguments"
    if "out of memory" in lowered or "cannot allocate memory" in lowered or "killed" in lowered:
        return "resource_exhausted"
    return "process_failed"


def _failure_summary(category: str, last_line: str | None) -> str:
    """Render a short diagnosis summary."""
    if category == "permission_denied":
        return "Process failed with a permission error."
    if category == "path_missing":
        return "Process failed because an expected path was missing."
    if category == "invalid_arguments":
        return "Process failed because one or more launch arguments were invalid."
    if category == "resource_exhausted":
        return "Process failed because the runtime appears to have exhausted resources."
    if last_line:
        return f"Process failed. Last log line: {last_line}"
    return "Process failed without a diagnostic log line."
